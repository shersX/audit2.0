def count_chinese_chars(text: str) -> int:
    """
    统计中文字数（Unicode 范围 \u4e00-\u9fff）
    同时将连续英文/数字视为“一个字”（符合科研写作习惯）
    """
    # 提取所有中文字符
    chinese_chars = re.findall(r'[\u4e00-\u9fff]', text)
    # 提取英文单词和数字（避免把 'CRISPR-Cas9' 算成10个字符）
    english_words = re.findall(r'[a-zA-Z]+|\d+', text)
    #print(f"中文字符数: {len(chinese_chars)},英文单词/数字项数: {len(english_words)}")
    # 总“字数” ≈ 中文字符数 + 英文单词/数字项数
    return len(chinese_chars) + len(english_words)

def prompt_rule(modules, last_page_num, has_global_image,has_section23_image, has_tech_route_image):
    target_modules = [
        "封面",
        "一、课题项目概览",
        "二、立项依据",
        "三、项目的研究内容、研究目标，以及拟解决的关键科学问题",
        "四、拟采取的研究方案及可行性分析",
        "五、本项目的特色与创新之处"
    ]
    # 生成总文本
    total_text = "\n\n".join(f"{module}:\n{modules.get(module, '')}" for module in target_modules if modules.get(module, ''))
    # 模块3和4的内容处理
    content_module3 = modules["三、项目的研究内容、研究目标，以及拟解决的关键科学问题"]
    lenmodules3 = count_chinese_chars(content_module3)
    content_module4 = modules["四、拟采取的研究方案及可行性分析"]
    combined34 = f"【三、项目的研究内容、研究目标，以及拟解决的关键科学问题】\n{content_module3}\n\n【四、拟采取的研究方案及可行性分析】\n{content_module4}\n\n"
    
    # 模块5和6的内容处理
    content_module5 = modules["五、本项目的特色与创新之处"]
    content_module6 = modules["六、年度研究计划及预期研究结果"]
    combined56 = f"【五、本项目的特色与创新之处】\n{content_module5}\n\n【六、年度研究计划及预期研究结果】\n{content_module6}\n\n"
    
    # 提取团队分工信息
    pattern = re.compile(
        rf'({re.escape("课题参加人员")}.*?)(?={re.escape("课题主要内容、意义和预期成果")})',
        re.DOTALL
    )
    team_match = pattern.search(modules["一、课题项目概览"])
    team = team_match.group(1) if team_match else ""
    
    # 5. 生成所有prompt
    prompts = [
        module_1prompt(total_text, last_page_num,has_global_image),
        module_2prompt("【一、课题项目概览】\n" + modules["一、课题项目概览"]),
        module_3prompt("【二、立项依据】\n" + modules["二、立项依据"],has_section23_image),
        module_4prompt(combined34, lenmodules3,has_tech_route_image),
        module_5prompt(combined56),
        module_6prompt("【项目概览之团队分工】\n" + team + "\n\n" +
                    "【七、研究基础与工作条件】\n" + modules["七、研究基础与工作条件"] + "\n\n" +
                    "【八、申请人简介】\n" + modules["八、申请人简介"] + "\n\n" +
                    "【项目预算表】\n" + modules["项目预算表"])
    ]
    return prompts


