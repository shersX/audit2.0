"""模块三 Prompt：规则 18–26。"""

import datetime

from prompt.utils import count_chinese_chars


def module_3prompt(text,has_section23_image):
    current_year = datetime.datetime.now().year
    prompt = f"""
你是一名严谨的科研项目立项依据评估专家。请严格遵循以下【评估规则与符合性标准】，对用户提供的【立项依据】模块文本进行逐项、独立评估。

你必须执行统一判定流程（适用于规则18-26）：
1. **提取证据**：先定位立项依据中的对应证据（章节/段落/原文片段）。
2. **对照标准**：将证据与该规则“符合标准”逐项比对。
3. **输出结论**：仅输出“符合”或“不符合”。

### **【统一判定约束】**
- 所有规则均为二元判定，不得使用分数、满分、扣分、0/1、0/2等表述。
- 若证据不足或无法定位关键证据，默认判定为“不符合”，并在理由中写明“证据不足”。
- 为每项规则提供清晰、具体的理由，理由中需要列出每一处有问题的地方。
- 除指定JSON字段外，不得输出其他字段。

### **【评估规则与符合性标准】**
**规则：18.立项依据是否包含1）课题背景2）研究现状3）当前亟待解决的问题**
- 检查步骤：
  1) 拆分立项依据，检测是否存在清晰分段或显式表述；
  2) 分别定位三类要素，记录每类是否有可引用原文；
  3) 对每类做“有/无”判定。
- 要素定义（识别说明）：
  - ① **课题背景**：领域总体情况、研究意义、临床/行业需求（如“肿瘤耐药是临床治疗的主要瓶颈，严重影响患者预后”）；
  - ② **研究现状**：国内外研究进展、核心成果、主流观点（如“现有研究聚焦 XX 通路，已证实其在肿瘤增殖中的作用”）；
  - ③ **亟待解决的问题**：具体、聚焦的科学问题，非泛泛而谈（如“XX 通路在耐药中的调控机制尚未阐明，缺乏针对性干预靶点”）。
- 符合标准（AND）：三类要素均可在文本中识别。
- 不符合触发：任意一类缺失、仅泛泛表述无法对应上述定义、或证据不足（需列出缺失类及证据）。

**规则：19.立项依据是否结合对应文献和前期结果**
- 检查步骤：
  1) 提取立项依据中的关键论点（核心论断、机制推断、问题提出等）；
  2) 判定支撑类型为“文献支撑”或“前期结果支撑”。
- 识别说明（满足任一即视为该论点有支撑）：
  - 文献支撑：引用序号（如 [1]、[2-3]），或“XX 等（2023）研究发现”等明确文献表述；
  - 前期结果支撑：“本课题组前期实验发现”“预实验数据显示”“已发表成果证实”等。
- 符合标准：所有关键论点均有文献或前期结果支撑（每条论点至少一种即可）。
- 不符合触发：立项依据部分既无文献支撑也无前期结果支撑（需列出原文及缺失说明）。

**规则：20.立项依据部分，引用文献对应的内容是否真实**
- 检查步骤：
  1) 提取引用标注（如[1]、[5-7]）及其对应论述；
  2) 核查是否存在空引（例如文献引用是[36]，但参考文献列表中没有[36]）、错配或明显不实映射。
- 符合标准：未发现空引或明显不实引用。
- 不符合触发：发现任意1处空引/错配（需给出证据）。

**规则：21.参考文献总数是否在30-50篇之间**
- 证据范围：【二、立项依据】末尾参考文献列表。
- 检查步骤：统计立项依据参考文献总数。
- 符合标准：30<=总数<=50。
- 不符合触发：总数<30 或 总数>50 或证据不足。

**规则：22.参考文献是否保持格式统一**
- 证据范围：【二、立项依据】末尾参考文献列表。
- **「格式统一」的含义**：全文参考文献属于**同一著录体系**（字段顺序、标点习惯、作者标注方式大体一致），不是要求每一条文献的字段集合完全相同。
- **检查步骤**：
  1) 逐条列出并审查全部参考文献；
  2) 对每一条对照**著录骨架**是否属于同一体系：作者 → 题名 → 期刊 → 卷期页 → 年份 →（可选）DOI；
  3) 汇总全部条目后，区分「体系混用」与「合理差异」（见下）；若存在中英文文献，须在全部条目中分别核对同类文献是否一致。
- **视为统一、判符合**（下列不单独构成不符合）：
  - 英文文献含 DOI、中文期刊文献无 DOI（国内期刊常无 DOI，不得仅因一条中文文献缺 DOI 而判全文不统一）；
  - 英文作者用「姓, 名缩写 et al.」、中文作者用「姓名 & 姓名」或「等」——**跨语种作者写法差异允许**；
  - 英文期刊用缩写、中文期刊用全称——若同类文献（英对英、中对中）各自一致，允许；
  - 个别条目缺卷期页中的某一段（如仅页码范围不同），但整体骨架与多数条目一致。
- **视为不统一、判不符合**（命中任一即不符合）：
  - 多套体系混用：如部分条目为「作者. 题名. 期刊 卷, 页 (年).」、另一部分为「作者, 题名, 期刊, 年, 卷(期):页」等明显不同著录模板随机交替；
  - 同类文献结构不一致：英文文献之间有的有 DOI、有的用完全不同字段顺序；或中文文献之间著录方式明显两套；
  - 混用编号体例与著者-出版年体例等根本不同的引用格式。
- 符合标准：全部参考文献属同一著录体系，仅存在上述允许的合理差异。
- 不符合触发：全部参考文献中存在明显多套著录模板混用或同类文献结构系统性不一致（须列出具体条目编号及差异点，**不得**仅以「一条中文文献无 DOI」为由判不符合）。

**规则：23.参考文献中是否包含近5年的研究，引用近5年研究的数量是否合适**
- 证据范围：【二、立项依据】末尾参考文献列表。
- 前置信息：当前年份为{current_year}，近5年范围为{current_year-5}年至{current_year}年。
- 检查步骤：统计近5年文献数量与占比。
- 符合标准（AND）：包含近5年文献，且近5年文献占比>=40%。
- 不符合触发：无近5年文献，或占比<40%，或证据不足。

**规则：24.立项依据部分是否有子标题**
- 检查步骤：定位立项依据中是否存在带序号层级标题（如“（一）”“1.1”）。
- 符合标准：存在清晰的序号化子标题结构。
- 不符合触发：无子标题或层级结构明显不清（需给出证据）。

**规则：25.立项依据是否附有图文**
- 前置信息：立项依据是否附有图文 = {"有" if has_section23_image else "无"}。
- 符合标准：有图文。
- 不符合触发：无图文或证据不足。

**规则：26.立项依据部分所有文字是否超过4000字**
- 前置信息：文本字数 = {count_chinese_chars(text)}。
- 检查标准：超过4000字（可偏差至4400字）判定为不符合；4400及以下判定为符合。
- 不符合触发：字数>4400 或证据不足。

### **【输出要求】**
请输出一个**JSON数组**，包含9个对象，分别对应规则18至26。每个对象必须严格包含以下三个键：
- "规则内容": 填写对应规则描述（需带规则序号）。
- "理由": 填写相应的理由。
- "是否符合": 只能填写"符合"或"不符合"。

### **【输出格式示例】**
[
  {{
    "规则内容": "18.立项依据是否包含1）课题背景2）研究现状3）当前亟待解决的问题",
    "理由": "文本缺少对'当前亟待解决的问题'的明确阐述。",
    "是否符合": "不符合"
  }}
]

### **【待评估文本】**
{text}
    """
    return prompt

